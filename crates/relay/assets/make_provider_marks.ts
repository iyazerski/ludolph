// Writes provider-marks.js: the model providers' marks the desktop shows by
// each chat and model, for the providers agents use most. They come from
// rune-theme-opencode's provider icons (the ones the Companion draws), so both
// look the same. Run: bun make_provider_marks.ts <rune checkout>/themes/opencode/src/provider_icons.rs

const PROVIDERS = [
  "anthropic", "openai", "google", "xai", "mistral", "deepseek", "groq", "openrouter", "amazon-bedrock",
  "azure", "github-copilot", "cerebras", "fireworks-ai", "togetherai", "moonshotai",
  "zai", "zai-coding-plan", "minimax", "perplexity", "cohere", "alibaba", "opencode", "vercel", "nvidia",
  "meta", "llama",
];

const src = await Bun.file(process.argv[2]).text();
const marks: Record<string, [number, string]> = {};
for (const m of src.matchAll(/static \w+: Icon = Icon \{\s*name: "([^"]*)",\s*view: ([\d.]+),\s*body: r##"([\s\S]*?)"##/g)) {
  if (PROVIDERS.includes(m[1])) marks[m[1]] = [Number(m[2]), m[3]];
}
const missing = PROVIDERS.filter(p => !marks[p]);
if (missing.length) throw new Error(`no marks for ${missing.join(", ")}`);

const out = `// Generated by make_provider_marks.ts from rune-theme-opencode's provider icons. Do not edit.
"use strict";
const PROVIDER_MARKS = ${JSON.stringify(Object.fromEntries(PROVIDERS.map(p => [p, marks[p]])))};
`;
await Bun.write(new URL("provider-marks.js", import.meta.url), out);
console.log(`${PROVIDERS.length} marks, ${out.length} bytes`);
